"""Puertos (interfaces) de persistencia.

La capa de aplicación depende únicamente de estos `Protocol`, nunca de
SQLAlchemy. La capa de infraestructura los implementa contra Postgres.
Esto es lo que permite testear los casos de uso con repositorios falsos
y cambiar de motor de base de datos sin tocar la lógica de negocio.
"""
from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from typing import Protocol

from app.domain.entities import (
    CajaTurno,
    Categoria,
    Cliente,
    Empresa,
    MovimientoCaja,
    MovimientoCuentaCorriente,
    MovimientoInventario,
    OrdenCompra,
    OrdenEnvio,
    PedidoCliente,
    Producto,
    Proveedor,
    ProveedorProducto,
    ReclamoProveedor,
    ResolucionNoVendible,
    SolicitudPresupuesto,
    StockNoVendible,
    Usuario,
    VentaMostrador,
)
from app.domain.enums import RolUsuario


class UsuarioRepository(Protocol):
    def get_by_id(self, usuario_id: int) -> Usuario | None: ...
    def get_by_email(self, email: str) -> Usuario | None: ...
    def add(self, usuario: Usuario) -> Usuario: ...
    def update(self, usuario: Usuario) -> Usuario: ...
    def list_by_rol(self, rol: str) -> list[Usuario]: ...
    def list_internos(self) -> list[Usuario]: ...
    def contar_internos(self, rol: RolUsuario | None = None, solo_activos: bool = False) -> int: ...


class IntentoLoginRepository(Protocol):
    def contar_recientes(self, ventana_segundos: int, email: str | None = None, ip: str | None = None) -> int: ...
    def registrar_fallo(self, email: str, ip: str | None) -> None: ...
    def limpiar(self, email: str, ip: str | None, mas_viejos_que_segundos: int) -> None: ...


class EmpresaRepository(Protocol):
    def get(self) -> Empresa: ...
    def save(self, empresa: Empresa) -> Empresa: ...


class CategoriaRepository(Protocol):
    def list(self, solo_activas: bool = False) -> list[Categoria]: ...
    def get_by_id(self, categoria_id: int) -> Categoria | None: ...
    def add(self, categoria: Categoria) -> Categoria: ...
    def update(self, categoria: Categoria) -> Categoria: ...
    def delete(self, categoria_id: int) -> None: ...
    def existe_nombre(self, nombre: str, excluir_id: int | None = None) -> bool: ...


class ProductoRepository(Protocol):
    def list(
        self, solo_activos: bool = False, categoria_id: int | None = None, busqueda: str | None = None
    ) -> list[Producto]: ...
    def get_by_id(self, producto_id: int) -> Producto | None: ...
    def get_by_codigo(self, codigo: str) -> Producto | None: ...
    def buscar(self, texto: str, limite: int = 20) -> list[Producto]: ...
    def add(self, producto: Producto) -> Producto: ...
    def update(self, producto: Producto) -> Producto: ...
    def delete(self, producto_id: int) -> None: ...
    def siguiente_codigo(self) -> str: ...
    def tiene_historial(self, producto_id: int) -> bool: ...
    def bloquear(self, producto_ids) -> None: ...


